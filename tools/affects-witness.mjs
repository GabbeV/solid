// Canonical witness data, not a scheduler or expected-value engine. The
// independent kernel checks each actual core.step for all numeric inputs.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'solid-affects-witness-'));
try{
const emitted=path.join(dir,'driver.mjs');
const built=spawnSync(path.join(root,'node_modules/.bin/bun'),['upstream/bend/bend2/main.ts','proof/affects-driver.bend','-o',emitted],{cwd:root,encoding:'utf8'});
if(built.status!==0)throw Error(built.stderr);
const {default:D}=await import(pathToFileURL(emitted));
const constructors=new Map();
function split(text){let depth=0,start=0,out=[];for(let i=0;i<text.length;i++){if('<({'.includes(text[i]))depth++;if('>)}'.includes(text[i]))depth--;if(text[i]===','&&depth===0){out.push(text.slice(start,i).trim());start=i+1;}}if(text.slice(start).trim())out.push(text.slice(start).trim());return out;}
for(const [file,ns]of[['representation/records.bend','R'],['runtime/core.bend','C']]){
 let data=false;for(const line of fs.readFileSync(root+'/'+file,'utf8').split('\n')){
  if(/^type .* is Data:/.test(line)){data=true;continue;}if(/^[^ #\t]/.test(line))data=false;if(!data)continue;
  const m=line.match(/^  (\w+)\{(.*)\}$/);if(!m)continue;
  constructors.set(m[1],{ns,fields:split(m[2]).map(x=>{const i=x.indexOf(':');return[x.slice(0,i).trim(),x.slice(i+1).trim()];})});
 }
}
function show(value,type){
 type=type.replace(/\b[RC]\./g,'');
 if(type==='Nat')return value+'n';if(type==='U32')return String(value);if(type==='Bool')return value?'True{}':'False{}';if(type==='String')return JSON.stringify(value);
 if(type.startsWith('List<')){const elem=split(type.slice(5,-1))[1],items=[];while('head'in value){items.push(show(value.head,elem));value=value.tail;}return '['+items.join(', ')+']';}
 if(type==='Value'&&value.$==='Number'&&value.n===11)return 'R.Number{initial}';
 const con=constructors.get(value.$);if(!con)throw Error('Unknown '+type+' '+JSON.stringify(value));
 return con.ns+'.'+value.$+'{'+con.fields.map(([name,t])=>{if(value[name]===undefined)throw Error('Missing '+value.$+'.'+name+' keys '+Object.keys(value));return show(value[name],t);}).join(', ')+'}';
}
let m=D.before(11),states=[m];
for(let i=0;i<128&&'head'in m.tasks;i++){m=D.step(m);states.push(m);}
if('head'in m.tasks||m.world.fault.$!=='Healthy')throw Error('Optimistic witness did not finish');
const steps=states.length-1;if(steps!==51)throw Error('Review changed affects execution length '+steps);
let out=`# Generated by tools/affects-witness.mjs using actual core.step.
# Every step and complete-machine claim is independently kernel checked.
import Base
import ../runtime/core.bend as C
import ../representation/records.bend as R
import ../representation/base.bend as B
import ./paths.bend as P
import ./affects-driver.bend as Driver

`;
for(let i=0;i<states.length;i++)out+=`def state_${i}(+initial: Nat) -> C.Machine:
  ${show(states[i],'Machine')}

`;
for(let i=0;i<steps;i++)out+=`def step_${i}(+initial: Nat) -> {C.step(state_${i}(initial)) == state_${i+1}(initial) : C.Machine}:
  {==}

`;
out+=`def witness(+initial: Nat) -> P.Path<state_0(initial), state_${steps}(initial)>:
  `;
for(let i=0;i<steps;i++)out+=`P.PathStep{state_${i+1}(initial), step_${i}(initial), `;
out+=`P.PathEnd{${show(m.world,'World')}, [R.ArrayReference{0n}], {==}, {==}}`+'}'.repeat(steps)+'\n';
out+=`
def entry(+initial: Nat) -> {Driver.before(initial) == state_0(initial) : C.Machine}:
  {==}

def connect(-fuel: Nat, -start: C.Machine, -canonical: C.Machine, -end: C.Machine, linked: {start == canonical : C.Machine}, run: {C.run(fuel, canonical) == end : C.Machine}) -> {C.run(fuel, start) == end : C.Machine}:
  Equal.trans(C.Machine, C.run(fuel, start), C.run(fuel, canonical), end, Equal.cong(C.Machine, C.Machine, m => C.run(fuel, m), start, canonical, linked), run)

def complete(+initial: Nat, +extra: Nat) -> {C.run(Nat.add(${steps}n, extra), Driver.before(initial)) == state_${steps}(initial) : C.Machine}:
  connect(Nat.add(${steps}n, extra), Driver.before(initial), state_0(initial), state_${steps}(initial), entry(initial), P.retimed(state_0(initial), state_${steps}(initial), witness(initial), extra, Nat.add(${steps}n, extra), {==}))

def outputs(+initial: Nat) -> List<&2, R.ArrayData>:
  [R.ArrayData{[R.Present{R.Boolean{True{}}}, R.Present{R.Boolean{False{}}}, R.Present{R.Number{initial}}]}]

def arraysOf(-actual: C.Machine, -w: R.World, +arrays: List<&2, R.ArrayData>, run: {actual == C.Machine{w, [], [R.ArrayReference{0n}]} : C.Machine}, data: {R.World.arrays(w) == arrays : List<&2, R.ArrayData>}) -> {R.World.arrays(C.world(actual)) == arrays : List<&2, R.ArrayData>}:
  Equal.trans(List<&2, R.ArrayData>, R.World.arrays(C.world(actual)), R.World.arrays(w), arrays, Equal.cong(C.Machine, List<&2, R.ArrayData>, m => R.World.arrays(C.world(m)), actual, C.Machine{w, [], [R.ArrayReference{0n}]}, run), data)

def result(+initial: Nat, extra: Nat) -> {R.World.arrays(C.world(C.run(Nat.add(${steps}n, extra), Driver.before(initial)))) == outputs(initial) : List<&2, R.ArrayData>}:
  arraysOf(C.run(Nat.add(${steps}n, extra), Driver.before(initial)), C.world(state_${steps}(initial)), outputs(initial), complete(initial, extra), {==})
`;
const dest=path.join(root,'proof/affects-program.bend');
if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8')!==out)throw Error('Optimistic witness is stale');}else fs.writeFileSync(dest,out);
console.log(`${steps} actual constructor/setter/flush/read steps have a canonical proof path.`);
}finally{fs.rmSync(dir,{recursive:true,force:true});}
