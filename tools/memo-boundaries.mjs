// Untrusted helper/constructor snapshots from the actual emitted definitions.
// The independent kernel checks every equation and the complete public program.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
function serializer(root,generalInitial=false){
const variable=generalInitial?'initial':'input';
const constructors=new Map();
function split(text){let depth=0,start=0,out=[];for(let i=0;i<text.length;i++){if('<({'.includes(text[i]))depth++;if('>)}'.includes(text[i]))depth--;if(text[i]===','&&depth===0){out.push(text.slice(start,i).trim());start=i+1;}}if(text.slice(start).trim())out.push(text.slice(start).trim());return out;}
for(const [file,ns]of[['representation/records.bend','R'],['runtime/core.bend','C'],['runtime/owner.bend','O'],['runtime/pending.bend','Q']]){
 let data=false,family;for(const line of fs.readFileSync(root+'/'+file,'utf8').replace(/\n    /g,' ').split('\n')){
  if(/^type .* is Data:/.test(line)){data=true;family=line.match(/^type (\w+)/)[1];continue;}if(/^[^ #\t]/.test(line))data=false;if(!data)continue;
  const m=line.match(/^  (\w+)\{(.*)\}$/);if(!m)continue;
  constructors.set(ns+'.'+family+'.'+m[1],{ns,fields:split(m[2]).map(x=>{const i=x.indexOf(':');return[x.slice(0,i).trim(),x.slice(i+1).trim()];})});
 }
}
const shared=new Map(),declarations=[];
function qualified(type,ns){
 if(['Nat','Bool','U32','String'].includes(type))return type;
 if(type.startsWith('List<'))return 'List<&2, '+qualified(split(type.slice(5,-1))[1],ns)+'>';
 return type.includes('.')?type:ns+'.'+type;
}
function intern(body,type){
 const key=type+'#'+body;if(shared.has(key))return shared.get(key);
 const name='data_'+shared.size,open=new RegExp('\\b'+variable+'\\b').test(body),call=name+(open?'('+variable+')':'()');shared.set(key,call);
 declarations.push(`def ${name}(${open?'+'+variable+': Nat':''}) -> ${type}:\n  ${body}\n`);return call;
}
function show(value,type,ns='R'){
 const plain=type.replace(/^\w+\./,'');
 if(plain==='Nat')return value+'n';if(plain==='U32')return String(value);if(plain==='Bool')return value?'True{}':'False{}';if(plain==='String')return JSON.stringify(value);
 if(type.startsWith('List<')){const elem=split(type.slice(5,-1))[1],items=[];while('head'in value){items.push(show(value.head,elem,ns));value=value.tail;}return intern('['+items.join(', ')+']',qualified(type,ns));}
 const family=type.includes('.')?type:ns+'.'+type;
 if(family==='R.Value'&&value.$==='Number'){
  const terms=generalInitial?{11:'initial',12:'Nat.add(initial, 1n)'}:{17:'input',18:'Nat.add(input, 1n)'};
  if(terms[value.n])return intern('R.Number{'+terms[value.n]+'}','R.Value');
 }
 const con=constructors.get(family+'.'+value.$);if(!con)throw Error('Unknown '+type+' '+JSON.stringify(value));
 return intern(con.ns+'.'+value.$+'{'+con.fields.map(([name,t])=>{if(value[name]===undefined)throw Error('Missing '+value.$+'.'+name+' keys '+Object.keys(value));return show(value[name],t,con.ns);}).join(', ')+'}',qualified(type,ns));
}
return {show,declarations};
}

const header=`# Generated by tools/memo-boundaries.mjs from actual source helpers/core.step.
# Data generation is untrusted; the independent kernel checks the equations.
import Base
import ../representation/records.bend as R
import ../runtime/core.bend as C
import ../runtime/owner.bend as O
import ../runtime/pending.bend as Q

`;
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'solid-memo-boundaries-'));
try{
for(const phase of ['setter','constructor','initial']){
 const emitted=path.join(dir,phase+'.mjs');
 const built=spawnSync(path.join(root,'node_modules/.bin/bun'),['upstream/bend/bend2/main.ts','proof/memo-'+phase+'-driver.bend','-o',emitted],{cwd:root,encoding:'utf8'});
 if(built.status!==0)throw Error(built.stderr);
 const {default:D}=await import(pathToFileURL(emitted)),{show,declarations}=serializer(root,phase==='initial');
 let body='';
 if(phase==='setter'){
  for(const name of ['origin','queued','slotted','stamped','inserted','scheduled'])body+=`def ${name}(${['origin','queued'].includes(name)?'':'+input: Nat'}) -> R.World:\n  ${show(D[name](17),'World')}\n\n`;
 }else{
  const generic=phase==='initial',args=generic?'initial':'',params=generic?'+initial: Nat':'';
  let machine=D.before(generic?11:undefined),states=[machine];
  for(let i=0;i<256&&'head'in machine.tasks;i++){machine=D.step(machine);states.push(machine);}
  if('head'in machine.tasks||machine.world.fault.$!=='Healthy'||states.length!==15)throw Error('Memo constructor witness requires source review');
  for(let i=0;i<states.length;i++)body+=`def state_${i}(${params}) -> C.Machine:\n  ${show(states[i],'C.Machine')}\n\n`;
  body+=`def finished(${params}) -> R.World:\n  ${show(D.finish(machine.world),'World')}\n`;
  let steps=`# Generated witness equations; each is independently checked.\nimport Base\nimport ../runtime/core.bend as C\nimport ./memo-${phase}-data.bend as D\n`;
  for(let i=0;i<14;i++)steps+=`\ndef step_${i}(${params}) -> {C.step(D.state_${i}(${args})) == D.state_${i+1}(${args}) : C.Machine}:\n  {==}\n`;
  output('proof/memo-'+phase+'-steps.bend',steps);
 }
 output('proof/memo-'+phase+'-data.bend',header+declarations.join('\n')+'\n'+body);
}
console.log(process.argv.includes('--check')?'Memo constructor/setter canonical data are current.':'Regenerated memo boundary data; run the independent kernel before trusting it.');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
function output(file,text){
 const target=path.join(root,file);
 if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==text)throw Error('Stale memo boundary data: '+file);}
 else fs.writeFileSync(target,text);
}
