"""Generate Bend's explicit record projections/rebuilders. No runtime logic."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
schemas={
'Node': [('kind','NodeKind'),('value','Value'),('pending','Slot'),('equals','Bool'),('config','U32'),('flags','U32'),('status','U32'),('time','Nat'),('notified','Nat'),('deps','Nat'),('depsTail','Nat'),('depGen','Nat'),('subs','Nat'),('subsTail','Nat'),('height','Nat'),('nextHeap','Nat'),('prevHeap','Nat'),('parent','Nat'),('firstChild','Nat'),('nextSibling','Nat'),('prevSibling','Nat'),('expr','Expr'),('modified','Bool'),('prevValue','Value'),('target','Nat'),('loading','Bool')],
'Link': [('dep','Nat'),('sub','Nat'),('nextDep','Nat'),('prevSub','Nat'),('nextSub','Nat'),('gen','Nat')],
'TreeNode': [('parent','Nat'),('children','List<&2, Nat>'),('text','Value')],
'World': [('nodes','List<&2, Node>'),('links','List<&2, Link>'),('buckets','List<&2, Nat>'),('minimum','Nat'),('maximum','Nat'),('marked','Bool'),('pendingNodes','List<&2, Nat>'),('trims','List<&2, Nat>'),('renderQueue','List<&2, Nat>'),('userQueue','List<&2, Nat>'),('context','Nat'),('tracking','Bool'),('running','Bool'),('scheduled','Bool'),('clock','Nat'),('epoch','Nat'),('tree','List<&2, TreeNode>'),('events','List<&2, TraceEvent>'),('fault','Fault'),('unflushedStaged','Bool'),('promotedWrites','List<&2, Nat>')]
}
header='''# Generated by tools/records.py; edit the schema, not the rebuilders.
import Base

type Value is Data:
  Undefined{}
  Null{}
  Boolean{b: Bool}
  Number{n: Nat}
  Reference{id: Nat}
  NotANumber{}
  StringValue{s: String}

type Slot is Data:
  Empty{}
  Present{value: Value}

type NodeKind is Data:
  Invalid{}
  Signal{}
  Memo{}
  Render{}
  User{}
  Root{}

type Expr is Data:
  Literal{value: Value}
  Read{id: Nat}
  Previous{}
  Add{left: Expr, right: Expr}
  Multiply{left: Expr, right: Expr}
  Same{left: Expr, right: Expr}
  Select{condition: Expr, yes: Expr, no: Expr}
  Untracked{body: Expr}
  Raise{cause: Value}

type Fault is Data:
  Healthy{}
  Exhausted{}
  BadId{}
  Unsupported{reason: Nat}
  TypeError{}

type TraceEvent is Data:
  Invoked{id: Nat}
  ReadValue{reader: Nat, source: Nat, value: Value}
  Applied{id: Nat, value: Value, previous: Value}
  Wrote{id: Nat, value: Value}
  Disposed{id: Nat}

'''
out=header
for name,fields in schemas.items():
    out+=f'type {name} is Data:\n  {name}'+'{'+', '.join(f'{n}: {t}' for n,t in fields)+'}\n\n'
    args=', '.join(n for n,_ in fields)
    for n,t in fields:
        out+=f'def {name}.{n}(r: {name}) -> {t}:\n  match r:\n    case {name}'+'{'+args+'}:\n      '+n+'\n\n'
        out+=f'def {name}.with_{n}(r: {name}, v: {t}) -> {name}:\n  match r:\n    case {name}'+'{'+args+'}:\n      '+name+'{'+', '.join('v' if k==n else k for k,_ in fields)+'}\n\n'
out=out.rstrip()+'\n'
target=root/'representation/records.bend'
import sys
if '--check' in sys.argv:
    if target.read_text()!=out: raise SystemExit('Generated record helpers are stale')
else:
    target.write_text(out)
